"""Pack the offline management page into a deterministic, flash-resident asset."""
import gzip
from pathlib import Path
import sys


def pack(source, output):
    data = Path(source).read_bytes()
    compressed = gzip.compress(data, compresslevel=9, mtime=0)
    # Python 3.11/3.12 may inherit zlib's platform-specific OS byte with mtime=0.
    compressed = compressed[:9] + b"\xff" + compressed[10:]
    if len(compressed) > 32768:
        raise ValueError("Web UI exceeds its 32 KiB compressed flash budget")
    rows = [", ".join(f"0x{byte:02x}" for byte in compressed[i:i + 16])
            for i in range(0, len(compressed), 16)]
    text = ("/* Generated by pack_webui.py; do not edit. */\n#include <stddef.h>\n"
            "const unsigned char webui_gzip[] = {\n" + ",\n".join(rows) +
            "\n};\nconst size_t webui_gzip_size = sizeof(webui_gzip);\n")
    Path(output).parent.mkdir(parents=True, exist_ok=True)
    Path(output).write_text(text, encoding="utf-8", newline="\n")
    print(f"Web UI: {len(data)} bytes -> {len(compressed)} bytes in flash")


if __name__ == "__main__":
    pack(*sys.argv[1:])
